"""Generate main/msg_bitmap.h: 1-bit bitmaps of fixed CJK messages (dev-time tool)."""
import sys
from PIL import Image, ImageDraw, ImageFont
FONT = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc"
MSGS = {"no_tf": "未检测到 TF 卡", "no_img": "TF 卡中没有图片", "hint": "请插入 FAT32 TF 卡后按复位键"}
SIZES = {"no_tf": 56, "no_img": 48, "hint": 26}
out = ["/* Generated by tools/hueleaf-push/gen_cjk_bitmap.py (Noto Sans CJK, OFL). */",
       "#pragma once", "#include <stdint.h>",
       "typedef struct { uint16_t w, h; const uint8_t *bits; } msg_bitmap_t; /* row-major, MSB first */"]
for key, text in MSGS.items():
    f = ImageFont.truetype(FONT, SIZES[key])
    l, t, r, b = f.getbbox(text)
    w, h = r - l + 4, b - t + 4
    im = Image.new("1", (w, h), 0)
    ImageDraw.Draw(im).text((2 - l, 2 - t), text, font=f, fill=1)
    stride = (w + 7) // 8
    data = bytearray(stride * h)
    px = im.load()
    for y in range(h):
        for x in range(w):
            if px[x, y]:
                data[y * stride + x // 8] |= 0x80 >> (x % 8)
    out.append(f"static const uint8_t k_{key}_bits[] = {{" + ",".join(str(v) for v in data) + "};")
    out.append(f"static const msg_bitmap_t k_msg_{key} = {{{w}, {h}, k_{key}_bits}};")
open(sys.argv[2] if len(sys.argv) > 2 else "msg_bitmap.h", "w").write("\n".join(out) + "\n")
